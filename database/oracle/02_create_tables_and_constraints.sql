-- Xóa bảng cũ nếu tồn tại (theo thứ tự quan hệ khóa ngoại)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- 1. BẢNG KHU_VUC (Khu vực bàn: Tầng 1, Sân vườn, Phòng lạnh, Ban công)
CREATE TABLE KHU_VUC (
    MaKhuVuc    VARCHAR2(10) NOT NULL,
    TenKhuVuc   NVARCHAR2(50) NOT NULL,
    GhiChu      NVARCHAR2(200),
    CONSTRAINT PK_KHU_VUC PRIMARY KEY (MaKhuVuc)
);

-- 2. BẢNG BAN (Bàn phục vụ trong quán)
CREATE TABLE BAN (
    MaBan       VARCHAR2(10) NOT NULL,
    TenBan      NVARCHAR2(50) NOT NULL,
    SoGhe       NUMBER(3) DEFAULT 4 NOT NULL,
    TrangThai   NVARCHAR2(20) DEFAULT 'TRONG' NOT NULL, -- TRONG, DANG_NGOI, DA_DAT
    MaKhuVuc    VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_BAN PRIMARY KEY (MaBan),
    CONSTRAINT FK_BAN_KHUVUC FOREIGN KEY (MaKhuVuc) REFERENCES KHU_VUC(MaKhuVuc) ON DELETE CASCADE,
    CONSTRAINT CK_BAN_SOGHE CHECK (SoGhe > 0),
    CONSTRAINT CK_BAN_TRANGTHAI CHECK (TrangThai IN ('TRONG', 'DANG_NGOI', 'DA_DAT'))
);

-- 3. BẢNG LOAI_MON (Danh mục nhóm đồ uống / món ăn)
CREATE TABLE LOAI_MON (
    MaLoai      VARCHAR2(10) NOT NULL,
    TenLoai     NVARCHAR2(50) NOT NULL,
    MoTa        NVARCHAR2(200),
    CONSTRAINT PK_LOAI_MON PRIMARY KEY (MaLoai)
);

-- 4. BẢNG MON (Thực đơn đồ uống và bánh ngọt)
CREATE TABLE MON (
    MaMon       VARCHAR2(10) NOT NULL,
    TenMon      NVARCHAR2(100) NOT NULL,
    DonViTinh   NVARCHAR2(20) DEFAULT 'Ly' NOT NULL,
    DonGia      NUMBER(12,2) NOT NULL,
    TrangThai   NVARCHAR2(20) DEFAULT 'CON_HANG' NOT NULL, -- CON_HANG, HET_HANG
    MaLoai      VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_MON PRIMARY KEY (MaMon),
    CONSTRAINT FK_MON_LOAIMON FOREIGN KEY (MaLoai) REFERENCES LOAI_MON(MaLoai),
    CONSTRAINT CK_MON_DONGIA CHECK (DonGia >= 0),
    CONSTRAINT CK_MON_TRANGTHAI CHECK (TrangThai IN ('CON_HANG', 'HET_HANG'))
);

-- 5. BẢNG CHUC_VU (Chức vụ của nhân viên trong quán café)
CREATE TABLE CHUC_VU (
    MaCV        VARCHAR2(10) NOT NULL,
    TenCV       NVARCHAR2(50) NOT NULL,
    LuongCoBan  NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_CHUC_VU PRIMARY KEY (MaCV),
    CONSTRAINT CK_CHUCVU_LUONG CHECK (LuongCoBan >= 0)
);

-- 6. BẢNG NHAN_VIEN (Nhân sự quán: Quản lý, Thu ngân, Pha chế, Phục vụ)
CREATE TABLE NHAN_VIEN (
    MaNV        VARCHAR2(10) NOT NULL,
    HoTen       NVARCHAR2(100) NOT NULL,
    GioiTinh    NVARCHAR2(10) DEFAULT 'Nam' NOT NULL,
    NgaySinh    DATE,
    SoDienThoai VARCHAR2(15) NOT NULL,
    DiaChi      NVARCHAR2(200),
    NgayVaoLam  DATE DEFAULT SYSDATE NOT NULL,
    TrangThai   NVARCHAR2(20) DEFAULT 'DANG_LAM' NOT NULL, -- DANG_LAM, DA_NGHI
    MaCV        VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_NHAN_VIEN PRIMARY KEY (MaNV),
    CONSTRAINT UQ_NV_SDT UNIQUE (SoDienThoai),
    CONSTRAINT FK_NV_CHUCVU FOREIGN KEY (MaCV) REFERENCES CHUC_VU(MaCV),
    CONSTRAINT CK_NV_GIOITINH CHECK (GioiTinh IN ('Nam', 'Nu', 'Khac')),
    CONSTRAINT CK_NV_TRANGTHAI CHECK (TrangThai IN ('DANG_LAM', 'DA_NGHI'))
);

-- 7. BẢNG KHACH_HANG (Khách hàng thân thiết / tích điểm)
CREATE TABLE KHACH_HANG (
    MaKH            VARCHAR2(10) NOT NULL,
    HoTen           NVARCHAR2(100) NOT NULL,
    SoDienThoai     VARCHAR2(15) NOT NULL,
    Email           VARCHAR2(100),
    DiemTichLuy     NUMBER(8) DEFAULT 0 NOT NULL,
    HangThanhVien   NVARCHAR2(20) DEFAULT 'DONG' NOT NULL, -- DONG, BAC, VANG, KIM_CUONG
    NgayDangKy      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_KHACH_HANG PRIMARY KEY (MaKH),
    CONSTRAINT UQ_KH_SDT UNIQUE (SoDienThoai),
    CONSTRAINT CK_KH_DIEM CHECK (DiemTichLuy >= 0),
    CONSTRAINT CK_KH_HANG CHECK (HangThanhVien IN ('DONG', 'BAC', 'VANG', 'KIM_CUONG'))
);

-- 8. BẢNG HOA_DON (Hóa đơn bán hàng / Order tại bàn hoặc mang về)
CREATE TABLE HOA_DON (
    MaHD            VARCHAR2(15) NOT NULL,
    NgayTao         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    TongTien        NUMBER(12,2) DEFAULT 0 NOT NULL,
    GiamGia         NUMBER(12,2) DEFAULT 0 NOT NULL,
    ThanhTien       NUMBER(12,2) DEFAULT 0 NOT NULL,
    PhuongThucTT    NVARCHAR2(30) DEFAULT 'TIEN_MAT' NOT NULL, -- TIEN_MAT, CHUYEN_KHOAN, THE
    TrangThai       NVARCHAR2(30) DEFAULT 'DA_THANH_TOAN' NOT NULL, -- CHO_THANH_TOAN, DA_THANH_TOAN, DA_HUY
    MaBan           VARCHAR2(10), -- Có thể NULL nếu khách mua mang về
    MaNV            VARCHAR2(10) NOT NULL,
    MaKH            VARCHAR2(10), -- Có thể NULL nếu khách vãng lai
    CONSTRAINT PK_HOA_DON PRIMARY KEY (MaHD),
    CONSTRAINT FK_HD_BAN FOREIGN KEY (MaBan) REFERENCES BAN(MaBan),
    CONSTRAINT FK_HD_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT FK_HD_KH FOREIGN KEY (MaKH) REFERENCES KHACH_HANG(MaKH),
    CONSTRAINT CK_HD_TIEN CHECK (TongTien >= 0 AND GiamGia >= 0 AND ThanhTien >= 0),
    CONSTRAINT CK_HD_TRANGTHAI CHECK (TrangThai IN ('CHO_THANH_TOAN', 'DA_THANH_TOAN', 'DA_HUY'))
);

-- 9. BẢNG CHI_TIET_HD (Chi tiết các món đồ uống trong hóa đơn)
CREATE TABLE CHI_TIET_HD (
    MaHD        VARCHAR2(15) NOT NULL,
    MaMon       VARCHAR2(10) NOT NULL,
    SoLuong     NUMBER(4) NOT NULL,
    DonGia      NUMBER(12,2) NOT NULL,
    ThanhTien   NUMBER(12,2) NOT NULL,
    GhiChu      NVARCHAR2(150), -- ví dụ: 50% đường, nhiều đá, ít sữa
    CONSTRAINT PK_CHI_TIET_HD PRIMARY KEY (MaHD, MaMon),
    CONSTRAINT FK_CTHD_HOADON FOREIGN KEY (MaHD) REFERENCES HOA_DON(MaHD) ON DELETE CASCADE,
    CONSTRAINT FK_CTHD_MON FOREIGN KEY (MaMon) REFERENCES MON(MaMon),
    CONSTRAINT CK_CTHD_SOLUONG CHECK (SoLuong > 0),
    CONSTRAINT CK_CTHD_DONGIA CHECK (DonGia >= 0)
);

-- 10. BẢNG NGUYEN_LIEU (Nguyên liệu trong kho quán café)
CREATE TABLE NGUYEN_LIEU (
    MaNL        VARCHAR2(10) NOT NULL,
    TenNL       NVARCHAR2(100) NOT NULL,
    DonViTinh   NVARCHAR2(20) NOT NULL, -- Kg, Hop, Chai, Goi
    SoLuongTon  NUMBER(10,2) DEFAULT 0 NOT NULL,
    DinhMucToiThieu NUMBER(10,2) DEFAULT 5 NOT NULL,
    CONSTRAINT PK_NGUYEN_LIEU PRIMARY KEY (MaNL),
    CONSTRAINT CK_NL_SOLUONG CHECK (SoLuongTon >= 0)
);

-- 11. BẢNG PHIEU_NHAP (Phiếu nhập kho nguyên liệu cà phê, sữa, siro...)
CREATE TABLE PHIEU_NHAP (
    MaPN        VARCHAR2(15) NOT NULL,
    NgayNhap    DATE DEFAULT SYSDATE NOT NULL,
    NhaCungCap  NVARCHAR2(150) NOT NULL,
    TongTien    NUMBER(12,2) DEFAULT 0 NOT NULL,
    MaNV        VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_PHIEU_NHAP PRIMARY KEY (MaPN),
    CONSTRAINT FK_PN_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
    CONSTRAINT CK_PN_TONGTIEN CHECK (TongTien >= 0)
);

-- 12. BẢNG CHI_TIET_PN (Chi tiết nguyên liệu trong phiếu nhập)
CREATE TABLE CHI_TIET_PN (
    MaPN        VARCHAR2(15) NOT NULL,
    MaNL        VARCHAR2(10) NOT NULL,
    SoLuong     NUMBER(10,2) NOT NULL,
    DonGiaNhap  NUMBER(12,2) NOT NULL,
    ThanhTien   NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_CHI_TIET_PN PRIMARY KEY (MaPN, MaNL),
    CONSTRAINT FK_CTPN_PHIEUNHAP FOREIGN KEY (MaPN) REFERENCES PHIEU_NHAP(MaPN) ON DELETE CASCADE,
    CONSTRAINT FK_CTPN_NGUYENLIEU FOREIGN KEY (MaNL) REFERENCES NGUYEN_LIEU(MaNL),
    CONSTRAINT CK_CTPN_SOLUONG CHECK (SoLuong > 0),
    CONSTRAINT CK_CTPN_DONGIA CHECK (DonGiaNhap >= 0)
);

-- 13. TẠO INDEX TỐI ƯU TRUY VẤN
CREATE INDEX IX_HD_NGAYTAO ON HOA_DON(NgayTao);
CREATE INDEX IX_HD_MABAN ON HOA_DON(MaBan);
CREATE INDEX IX_MON_MALOAI ON MON(MaLoai);
CREATE INDEX IX_NV_MACV ON NHAN_VIEN(MaCV);

COMMIT;
